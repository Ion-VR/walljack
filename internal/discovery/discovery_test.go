func parse(t *testing.T, frame []byte) Neighbor {
	t.Helper()
	p := gopacket.NewPacket(frame, layers.LinkTypeEthernet, gopacket.Default)
	n, ok := Parse(p)
	if !ok {
		t.Fatalf("Parse did not recognise the frame as a discovery advertisement")
	}
	return n
}

func TestParseLLDP(t *testing.T) {
	n := parse(t, lldpFrame)

	if n.Protocol != ProtocolLLDP {
		t.Errorf("Protocol = %q, want %q", n.Protocol, ProtocolLLDP)
	}
	for _, tc := range []struct{ name, got string }{
		{"ChassisID", n.ChassisID},
		{"PortID", n.PortID},
	} {
		if tc.got == "" {
			t.Errorf("%s is empty, the mandatory TLVs should always populate it", tc.name)
		}
	}
	if n.SystemName == "" {
		t.Errorf("SystemName is empty, this capture advertises one")
	}
	t.Logf("LLDP: %+v", n)
}

func TestParseCDP(t *testing.T) {
	n := parse(t, cdpFrame)

	if n.Protocol != ProtocolCDP {
		t.Errorf("Protocol = %q, want %q", n.Protocol, ProtocolCDP)
	}
	if n.ChassisID != "myswitch" {
		t.Errorf("ChassisID = %q, want %q", n.ChassisID, "myswitch")
	}
	if n.PortID != "FastEthernet0/1" {
		t.Errorf("PortID = %q, want %q", n.PortID, "FastEthernet0/1")
	}
	// This switch sends no System Name TLV, so the device ID should stand in.
	if n.SystemName != "myswitch" {
		t.Errorf("SystemName = %q, want the device ID to be used as a fallback", n.SystemName)
	}
	if n.Platform != "cisco WS-C2950-12" {
		t.Errorf("Platform = %q, want %q", n.Platform, "cisco WS-C2950-12")
	}
	if n.VLAN != "1" {
		t.Errorf("VLAN = %q, want %q (native VLAN)", n.VLAN, "1")
	}
	if n.ManagementIP != "192.168.0.253" {
		t.Errorf("ManagementIP = %q, want %q", n.ManagementIP, "192.168.0.253")
	}
	t.Logf("CDP: %+v", n)
}

func TestProtocolsProduceDistinctKeys(t *testing.T) {
	a := Neighbor{Protocol: ProtocolLLDP, ChassisID: "x", PortID: "y"}
	b := Neighbor{Protocol: ProtocolCDP, ChassisID: "x", PortID: "y"}
	if a.Key() == b.Key() {
		t.Errorf("a switch advertising both protocols should produce two keys, got %q twice", a.Key())
	}
}

func TestPrintableOrHex(t *testing.T) {
	cases := []struct {
		name string
		in   []byte
		want string
	}{
		// Vendors routinely null-pad fixed-width string TLVs. Before the trim
		// this came out as a hex blob instead of a readable switch name.
		{"null padded name", []byte("sw-access-3\x00\x00"), "sw-access-3"},
		{"plain name", []byte("Gi1/0/24"), "Gi1/0/24"},
		{"raw bytes", []byte{0x00, 0x1b, 0xff}, "0x001bff"},
		{"empty", []byte{}, ""},
		{"only padding", []byte("\x00\x00"), ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := printableOrHex(tc.in); got != tc.want {
				t.Errorf("printableOrHex(%q) = %q, want %q", tc.in, got, tc.want)
			}
		})
	}
}
